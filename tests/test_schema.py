def save_and_validate(data: Dict[str, Any], tmp_path: Path) -> Dict[str, Any]:
    """Helper to dump dictionary to temp file and run validate_file."""
    file_path = tmp_path / "test_candidate.json"
    with open(file_path, "w", encoding="utf-8") as f:
        json.dump(data, f)
    return validate_file(file_path)


def test_schema_file_exists():
    """Verify that docs/schema.json exists and is valid JSON."""
    schema_path = get_default_schema_path()
    assert schema_path.is_file(), f"Missing schema at {schema_path}"
    with open(schema_path, "r", encoding="utf-8") as f:
        schema = json.load(f)
    assert schema.get("$schema") == "https://json-schema.org/draft/2020-12/schema"
    assert schema.get("title") == "SPHEREx Sky Diary Contract Schema"


def test_validate_mock_output_file():
    """Validate data/output/candidates.json generated by mock generator."""
    candidates_file = Path("data/output/candidates.json")
    if not candidates_file.exists():
        pytest.skip("data/output/candidates.json does not exist yet.")

    data = validate_file(candidates_file)
    assert data["schema_version"] == "1.0"
    assert len(data["movers"]) >= 20
    assert len(data["epochs"]) >= 3

    # Rule 2 check: all synthetic data must have is_synthetic: true
    for mover in data["movers"]:
        assert mover["is_synthetic"] is True, f"Mover {mover['object_id']} must have is_synthetic: true"
        assert mover["type"] in ("known", "unknown")
        if mover["type"] == "known":
            assert mover["match_name"] is not None
        else:
            assert mover["match_name"] is None
        assert 0.0 <= mover["confidence"] <= 1.0


def test_minimal_payload_valid(valid_candidate_data, tmp_path):
    """Ensure baseline test fixture passes validation."""
    result = save_and_validate(valid_candidate_data, tmp_path)
    assert result["schema_version"] == "1.0"


def test_reject_missing_required_root_field(valid_candidate_data, tmp_path):
    """Rejection when required root fields are missing."""
    for required_field in ["schema_version", "region", "epochs", "movers"]:
        bad_data = copy.deepcopy(valid_candidate_data)
        del bad_data[required_field]
        with pytest.raises(ContractValidationError):
            save_and_validate(bad_data, tmp_path)


def test_reject_missing_mover_field(valid_candidate_data, tmp_path):
    """Rejection when required mover fields are missing."""
    for field in ["object_id", "ra", "dec", "type", "confidence", "is_synthetic", "motion", "detections"]:
        bad_data = copy.deepcopy(valid_candidate_data)
        del bad_data["movers"][0][field]
        with pytest.raises(ContractValidationError):
            save_and_validate(bad_data, tmp_path)


@pytest.mark.parametrize("bad_confidence", [1.05, 1.5, 2.0, -0.01, -1.0])
def test_reject_confidence_out_of_bounds(valid_candidate_data, tmp_path, bad_confidence):
    """Reject confidence scores outside [0.0, 1.0]."""
    bad_data = copy.deepcopy(valid_candidate_data)
    bad_data["movers"][0]["confidence"] = bad_confidence
    with pytest.raises(ContractValidationError) as excinfo:
        save_and_validate(bad_data, tmp_path)
    assert "confidence" in str(excinfo.value)


