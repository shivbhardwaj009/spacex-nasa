def test_reject_wrong_data_types(valid_candidate_data, tmp_path):
    """Reject non-conforming types (string instead of boolean/number)."""
    # is_synthetic as string
    bad_data1 = copy.deepcopy(valid_candidate_data)
    bad_data1["movers"][0]["is_synthetic"] = "true"
    with pytest.raises(ContractValidationError):
        save_and_validate(bad_data1, tmp_path)

    # ra as string
    bad_data2 = copy.deepcopy(valid_candidate_data)
    bad_data2["movers"][0]["ra"] = "269.5"
    with pytest.raises(ContractValidationError):
        save_and_validate(bad_data2, tmp_path)


def test_reject_spectrum_array_length_mismatch(valid_candidate_data, tmp_path):
    """Reject spectrum where wavelength_um, flux, and flux_err lengths differ."""
    # wavelength_um has 3 items, flux has 2 items
    bad_data = copy.deepcopy(valid_candidate_data)
    bad_data["movers"][0]["spectrum"]["flux"] = [10.0, 15.0]
    with pytest.raises(ContractValidationError) as excinfo:
        save_and_validate(bad_data, tmp_path)
    assert "spectrum array length mismatch" in str(excinfo.value)

    # flux_err has 4 items
    bad_data2 = copy.deepcopy(valid_candidate_data)
    bad_data2["movers"][0]["spectrum"]["flux_err"] = [0.5, 0.7, 1.0, 1.2]
    with pytest.raises(ContractValidationError) as excinfo:
        save_and_validate(bad_data2, tmp_path)
    assert "spectrum array length mismatch" in str(excinfo.value)


def test_reject_unknown_epoch_in_detection(valid_candidate_data, tmp_path):
    """Reject detections referencing an epoch_id not declared in top-level epochs."""
    bad_data = copy.deepcopy(valid_candidate_data)
    bad_data["movers"][0]["detections"][0]["epoch_id"] = "epoch_99_does_not_exist"
    with pytest.raises(ContractValidationError) as excinfo:
        save_and_validate(bad_data, tmp_path)
    assert "references unknown epoch_id" in str(excinfo.value)


def test_null_spectrum_is_valid(valid_candidate_data, tmp_path):
    """Spectrum is nullable in schema v1.0 for unextracted objects."""
    nullable_data = copy.deepcopy(valid_candidate_data)
    nullable_data["movers"][0]["spectrum"] = None
    result = save_and_validate(nullable_data, tmp_path)
    assert result["movers"][0]["spectrum"] is None

