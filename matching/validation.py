"""SPHEREx Catalog Matching - Validation Reporting.

Evaluates known asteroid recovery efficiency within the observation footprint
and produces validation_report.json and validation_report.md.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List

from matching.ephemeris import is_prediction_in_field
from matching.types import EphemerisPrediction, MatchRecord


def build_validation_report(
    candidates_payload: Dict[str, Any],
    predictions_by_epoch: Dict[str, List[EphemerisPrediction]],
    match_records: List[MatchRecord],
    output_dir: Path,
) -> Dict[str, Any]:
    """Generate validation report comparing predicted known objects vs recovered detections.

    Outputs:
    - data/output/validation_report.json
    - data/output/validation_report.md
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    json_path = output_dir / "validation_report.json"
    md_path = output_dir / "validation_report.md"

    region = candidates_payload.get("region", {})
    ra_center = region.get("ra_center", 269.452)
    dec_center = region.get("dec_center", 66.561)
    radius_deg = region.get("radius_deg", 0.5)

    # 1. Determine which known objects passed through the field during observation
    unique_objects = {}
    for ep_id, preds in predictions_by_epoch.items():
        for p in preds:
            in_field = is_prediction_in_field(p, ra_center, dec_center, radius_deg)
            if in_field:
                unique_objects.setdefault(p.object_name, []).append(ep_id)

    # Objects observable in at least 2 epochs
    observable_in_field = {
        name: ep_list for name, ep_list in unique_objects.items() if len(ep_list) >= 2
    }

    # 2. Match recovery
    recovered_matches = [m for m in match_records if m.is_matched]
    recovered_names = {m.match_name for m in recovered_matches if m.match_name}

    total_predicted = len(observable_in_field)
    total_recovered = len(recovered_names)
    recovery_fraction = (total_recovered / total_predicted) if total_predicted > 0 else 1.0

    unknown_candidates = [
        m for m in candidates_payload.get("movers", []) if m.get("type") == "unknown"
    ]

    report_data = {
        "report_generated_at": datetime.now(timezone.utc).isoformat(),
        "region_name": region.get("name", "Target Field"),
        "total_known_predicted_in_field": total_predicted,
        "total_known_recovered_by_detector": total_recovered,
        "recovery_fraction": round(recovery_fraction, 4),
        "recovery_percentage": round(recovery_fraction * 100.0, 1),
        "predicted_known_objects": list(observable_in_field.keys()),
        "recovered_known_objects": list(recovered_names),
        "unknown_candidates_detected": len(unknown_candidates),
        "matches": [
            {
                "candidate_id": m.candidate_id,
                "match_name": m.match_name,
                "designation": m.designation,
                "mean_distance_arcsec": m.mean_distance_arcsec,
                "velocity_diff_arcsec_day": m.velocity_diff_arcsec_day,
                "matched_epochs_count": m.matched_epochs_count,
            }
            for m in recovered_matches
        ],
    }

    # Save JSON report
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(report_data, f, indent=2)

    # Generate Markdown report
    md_content = f"""# SPHEREx Known Object Recovery Validation Report

**Generated:** {report_data['report_generated_at']}  
**Region:** {report_data['region_name']} (RA {ra_center:.3f}°, Dec {dec_center:.3f}°)  

---

## 📊 Summary Metrics

| Metric | Value |
|---|---|
| **Known Objects Predicted in Field** | {total_predicted} |
| **Known Objects Recovered by Detector** | {total_recovered} |
| **Catalog Recovery Fraction** | **{recovery_fraction * 100.0:.1f}%** |
| **Unmatched / Unknown Mover Candidates** | {len(unknown_candidates)} |

---

## 🎯 Recovered Known Asteroids / Comets

| Candidate ID | Matched Designation | Mean Astrometric Separation | Velocity Residual | Matched Epochs |
|---|---|---|---|---|
"""
    if recovered_matches:
        for m in recovered_matches:
            md_content += f"| `{m.candidate_id}` | **{m.match_name}** | {m.mean_distance_arcsec:.2f}\" | {m.velocity_diff_arcsec_day:.2f}\"/day | {m.matched_epochs_count} |\n"
    else:
        md_content += "| *None* | *No known bodies matched* | - | - | 0 |\n"

    md_content += f"""
---

## 🪐 Candidate Unknown Movers (Potential New Discoveries)
Total **{len(unknown_candidates)}** candidates exhibit coherent linear proper motion with no corresponding cataloged asteroid or comet in IMCCE SkyBoT / JPL Horizons.

---
*Report automatically generated by SPHEREx Sky Diary matching pipeline.*
"""
    with open(md_path, "w", encoding="utf-8") as f:
        f.write(md_content.strip() + "\n")

    return report_data
